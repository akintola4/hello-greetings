/**
 * Build-time loudness envelope for the ambient score.
 *
 * The visualiser beside the play button shows the actual music. Getting that
 * the obvious way — an `AnalyserNode` — means running the audio element through
 * `createMediaElementSource`, and on iOS that has historically put playback in
 * an audio session that obeys the silent switch. iOS 17 added a sanctioned fix
 * (`navigator.audioSession.type = 'playback'`), so the constraint is softer
 * than it was — but it is Safari-only, and a decorative meter does not justify
 * a platform-specific workaround when the loudness can simply be measured.
 *
 * So the loudness is measured once, here, and looked up at runtime by
 * `audio.currentTime`. It is real data about the real track, it costs no
 * AudioContext, and it stays accurate because it was computed from the file
 * that ships.
 *
 * Ten samples a second, each the RMS of its window, stretched across the
 * track's own dynamic range and quantised to a single base-36 digit. Roughly
 * 1.5 KB gzipped for five minutes of music.
 *
 * NOT wired into `prebuild`, unlike the other generators: it needs ffmpeg,
 * which is not on the CI image. Re-run it by hand when the track changes.
 *
 *   pnpm run envelope
 */
import { execFileSync } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TRACK = join(ROOT, 'public', 'audio', 'ambient-loop.mp3')
const OUT = join(ROOT, 'lib', 'audio', 'envelope.ts')

const RATE = 8000 // mono, downsampled — plenty for loudness
const HZ = 10 // envelope samples per second

let pcm
try {
  // s16le straight to stdout. `maxBuffer` because five minutes of 8 kHz mono is
  // about 4.6 MB and the default cap is 1 MB.
  pcm = execFileSync(
    'ffmpeg',
    ['-v', 'error', '-i', TRACK, '-ac', '1', '-ar', String(RATE), '-f', 's16le', '-'],
    { maxBuffer: 256 * 1024 * 1024 },
  )
} catch {
  console.error(
    '\n  Could not run ffmpeg.\n' +
      '  This script needs it to decode the track; install it with `brew install ffmpeg`.\n' +
      '  The committed envelope is still valid — you only need to regenerate it\n' +
      '  if you have changed public/audio/ambient-loop.mp3.\n',
  )
  process.exit(1)
}

const samples = new Int16Array(pcm.buffer, pcm.byteOffset, Math.floor(pcm.byteLength / 2))
const window = Math.floor(RATE / HZ)
const rms = []
for (let i = 0; i + window <= samples.length; i += window) {
  let sum = 0
  for (let k = 0; k < window; k++) {
    const v = samples[i + k] / 32768
    sum += v * v
  }
  rms.push(Math.sqrt(sum / window))
}

// Normalise against the track's own range, not against full scale. An ambient
// score never approaches 1.0, so a naive normalisation leaves every bar flat.
//
// Percentiles rather than min and max, because a single loud transient or a
// moment of near-silence would otherwise set the scale for the whole five
// minutes and flatten everything between them.
const sorted = [...rms].sort((a, b) => a - b)
const at = (q) => sorted[Math.floor(q * (sorted.length - 1))]
const floor = at(0.03)
const ceil = Math.max(floor + 1e-6, at(0.97))

// Perceptual, not linear: loudness is roughly a power law, and on a linear
// scale a quiet ambient track spends its whole life in the bottom two levels.
const levels = rms.map((v) => {
  const scaled = Math.max(0, Math.min(1, (v - floor) / (ceil - floor)))
  return Math.round(Math.pow(scaled, 0.7) * 35)
})

const encoded = levels.map((n) => n.toString(36)).join('')

await writeFile(
  OUT,
  `// GENERATED by scripts/generate-audio-envelope.mjs — do not edit by hand.
// Regenerate with \`pnpm run envelope\` when the track changes (needs ffmpeg).
//
// One base-36 digit per ${1000 / HZ}ms of ambient-loop.mp3: the RMS of that
// window, stretched from the track's 3rd percentile to its 97th and shaped by
// a 0.7 power curve so a quiet ambient score still moves across the full
// height. 0 is as quiet as this track gets, z is as loud.

/** Envelope samples per second. */
export const ENVELOPE_HZ = ${HZ}

/** Range-normalised loudness, one base-36 digit per sample. */
export const ENVELOPE =
  '${encoded}'

/**
 * Loudness at a moment in the track, 0–1.
 *
 * Wraps, because the score loops. Out-of-range and NaN times read as silence
 * rather than throwing — \`currentTime\` is briefly NaN while the element seeks.
 */
export function levelAt(seconds: number): number {
  if (!Number.isFinite(seconds) || ENVELOPE.length === 0) return 0
  const i = Math.floor(seconds * ENVELOPE_HZ) % ENVELOPE.length
  return parseInt(ENVELOPE[i < 0 ? i + ENVELOPE.length : i], 36) / 35
}
`,
)

const secs = (levels.length / HZ).toFixed(0)
console.log(`
  envelope  ${levels.length} samples  (${secs}s at ${HZ} Hz)
  size      ${(encoded.length / 1024).toFixed(1)} KB
  range     rms ${floor.toFixed(4)} – ${ceil.toFixed(4)} (3rd–97th pct)
`)
